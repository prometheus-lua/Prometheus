#!/usr/bin/env python3
"""Exercise source map generation and traceback rewriting through the CLI."""
import json
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
CLI = ROOT / "cli.lua"
LUA51 = "lua5.1"
LUAU = "luau"
TIMEOUT = 20


def run(command, cwd, *, input_text=None, timeout=TIMEOUT):
    return subprocess.run(command, cwd=cwd, input=input_text, text=True,
                          stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          timeout=timeout)


def check(command, cwd, *, input_text=None):
    result = run(command, cwd, input_text=input_text)
    assert result.returncode == 0, f"command failed ({result.returncode}): {command}\n{result.stdout}"
    return result.stdout


def fail(command, cwd, expected):
    result = run(command, cwd)
    assert result.returncode != 0, f"command unexpectedly succeeded: {command}\n{result.stdout}"
    assert expected in result.stdout, f"missing {expected!r}:\n{result.stdout}"
    return result.stdout


def lua_cli(*args, cwd):
    return [LUA51, str(CLI), *map(str, args)]


def traceback_command(map_path, trace_path="-"):
    return [LUA51, str(CLI), "trace", "--map", str(map_path), str(trace_path)]


def make_failure_sources(directory):
    # Shared leading whitespace, quoted string, and multiline literal exercise
    # source spans around syntax that occupies more than one generated line.
    prelude = '''-- source-map whitespace and literal coverage
local message = "quoted -- text"
local block = [=[
  multiline literal
]=]

'''
    cases = {
        "arithmetic": ("local function fail()\n"
                       "  local value = nil\n"
                       "  return value + 1\n"
                       "end\n\nfail()\n", 9),
        "indexing": ("local function fail()\n"
                     "  local value = {}\n"
                     "  return value.missing.member\n"
                     "end\n\nfail()\n", 9),
        "call": ("local function fail()\n"
                 "  local value = 42\n"
                 "  return value()\n"
                 "end\n\nfail()\n", 9),
        "closure": ("local captured = 1\n"
                    "local function outer()\n"
                    "  return function()\n"
                    "    return captured + nil\n"
                    "  end\n"
                    "end\n\nouter()()\n", 10),
        "multiline-index": ("local function fail()\n"
                            "  local target = nil\n"
                            "  return\n"
                            "    target\n"
                            "      [1]\n"
                            "end\n\nfail()\n", 10),
    }
    paths = {}
    for name, (body, expected_line) in cases.items():
        path = directory / f"original {name}: source.lua"
        path.write_text(prelude + body, encoding="utf-8", newline="")
        paths[name] = (path, expected_line, prelude + body)
    return paths


def generate(directory, source_path, output_path, map_path, target, pretty=False):
    args = ["--preset", "Minify", "--out", output_path.name, "--source-map", map_path.name,
            "--Lua51" if target == "Lua51" else "--LuaU"]
    if pretty:
        args.append("--pretty")
    args.append(source_path.relative_to(directory))
    check(lua_cli(*args, cwd=directory), directory)
    assert output_path.is_file(), output_path
    assert map_path.is_file(), map_path


with tempfile.TemporaryDirectory(prefix="prometheus-source-maps-") as temporary:
    base = Path(temporary)
    fixture_dir = base / "fixtures"
    fixture_dir.mkdir()
    cases = make_failure_sources(fixture_dir)

    # Both source targets and output layouts are generated by the CLI. Each
    # output is executed by both available runtimes to collect real tracebacks.
    for target in ("Lua51", "LuaU"):
        for pretty in (False, True):
            for name, (source_path, expected_line, source_text) in cases.items():
                case_dir = base / f"{target}-{int(pretty)}-{name}"
                case_dir.mkdir()
                local_source = case_dir / source_path.name
                local_source.write_bytes(source_path.read_bytes())
                output_path = case_dir / "generated output: sample.lua"
                map_path = case_dir / "generated output: sample.lua.map"
                generate(case_dir, local_source, output_path, map_path, target, pretty)

                source_map = json.loads(map_path.read_text(encoding="utf-8"))
                assert source_map["file"] == output_path.name, source_map
                assert source_map.get("sourcesContent", [None])[0] == source_text, source_map

                for runtime in (LUA51, LUAU):
                    if name == "multiline-index":
                        baseline = run([runtime, str(local_source)], case_dir)
                        assert baseline.returncode != 0, baseline.stdout
                        source_error = re.search(re.escape(local_source.name) + r":(\d+):", baseline.stdout)
                        assert source_error, baseline.stdout
                        baseline_line = int(source_error.group(1))
                        if name == "multiline-index":
                            # Lua runtimes may report either the base token or
                            # closing index token for this single AST span.
                            assert expected_line <= baseline_line <= expected_line + 1, baseline.stdout
                        else:
                            assert baseline_line == expected_line, baseline.stdout
                    result = run([runtime, str(output_path)], case_dir)
                    assert result.returncode != 0, f"expected {runtime} failure for {name}"
                    assert output_path.name in result.stdout, result.stdout
                    # Run every real runtime traceback through trace, reading
                    # from stdin, and retain C/unrelated frames verbatim.
                    raw_trace = result.stdout.rstrip() + (
                        "\n\t[C]: in function 'unrelated_c_frame'"
                        "\n\tother module.lua:77: in function 'unrelated'\n")
                    formatted = check(traceback_command(map_path), case_dir, input_text=raw_trace)
                    expected_location = f"original {name}: source.lua:{expected_line}"
                    if name == "multiline-index":
                        mapped_lines = (expected_line, expected_line + 1)
                        assert any(f"original {name}: source.lua:{line}" in formatted
                                   for line in mapped_lines), (runtime, expected_location, formatted)
                        assert any(f"> {line} | " in formatted for line in mapped_lines), (runtime, formatted)
                        assert "11 |       [1]" in formatted, formatted
                    else:
                        assert expected_location in formatted, (runtime, expected_location, formatted)
                        assert f"> {expected_line} | " in formatted, (runtime, formatted)
                    assert "[C]: in function 'unrelated_c_frame'" in formatted, formatted
                    assert "other module.lua:77: in function 'unrelated'" in formatted, formatted
                    if runtime == LUA51:
                        assert formatted.startswith("lua5.1: "), formatted

    # With source text omitted, trace resolves a relative source path from the
    # map's directory and emits the same excerpt.
    fallback_dir = base / "fallback"
    (fallback_dir / "sources").mkdir(parents=True)
    (fallback_dir / "build").mkdir()
    source_path = fallback_dir / "sources" / "without embedded source.lua"
    source_text = "local value = nil\nreturn value + 1\n"
    source_path.write_text(source_text, encoding="utf-8", newline="")
    config_path = fallback_dir / "source-map.config.lua"
    config_path.write_text("return { LuaVersion = 'Lua51', Steps = {}, SourceMap = true, "
                           "SourceMapIncludeSources = false }\n", encoding="utf-8")
    output_path = fallback_dir / "build" / "generated.lua"
    map_path = fallback_dir / "build" / "generated.lua.map"
    check(lua_cli("--config", config_path.name, "--Lua51", "--out", str(output_path),
                  "sources/without embedded source.lua", cwd=fallback_dir), fallback_dir)
    source_map = json.loads(map_path.read_text(encoding="utf-8"))
    assert "sourcesContent" not in source_map, source_map
    assert source_map["file"] == output_path.name, source_map
    assert source_map["sources"] == ["../sources/without embedded source.lua"], source_map
    runtime = run([LUA51, str(output_path)], fallback_dir)
    assert runtime.returncode != 0, runtime.stdout
    formatted = check(traceback_command(map_path), fallback_dir, input_text=runtime.stdout)
    assert "without embedded source.lua:2" in formatted, formatted
    assert "> 2 | return value + 1" in formatted, formatted

    # Relative input and map paths are rebased lexically without needing the
    # process working directory.
    relative_output = fallback_dir / "build" / "relative-generated.lua"
    check(lua_cli("--config", config_path.name, "--Lua51", "--out", "build/relative-generated.lua",
                  "sources/without embedded source.lua", cwd=fallback_dir), fallback_dir)
    relative_map = json.loads(Path(str(relative_output) + ".map").read_text(encoding="utf-8"))
    assert relative_map["sources"] == ["../sources/without embedded source.lua"], relative_map

    # On case-sensitive filesystems, a path component that differs only by
    # case is not part of the common prefix when rebasing absolute paths.
    case_root = base / "case-sensitive-paths"
    upper_source_dir = case_root / "Sources"
    lower_map_dir = case_root / "sources"
    upper_source_dir.mkdir(parents=True)
    try:
        lower_map_dir.mkdir()
        case_sensitive = not upper_source_dir.samefile(lower_map_dir)
    except FileExistsError:
        case_sensitive = False
    if case_sensitive:
        case_source = upper_source_dir / "file.lua"
        case_source.write_text(source_text, encoding="utf-8", newline="")
        case_output = lower_map_dir / "output.lua"
        check(lua_cli("--config", str(config_path), "--Lua51", "--out", str(case_output),
                      "Sources/file.lua", cwd=case_root), case_root)
        case_map_path = Path(str(case_output) + ".map")
        case_map = json.loads(case_map_path.read_text(encoding="utf-8"))
        assert case_map["sources"] == ["../Sources/file.lua"], case_map
        case_runtime = run([LUA51, str(case_output)], case_root)
        assert case_runtime.returncode != 0, case_runtime.stdout
        case_formatted = check(traceback_command(case_map_path), case_root,
                               input_text=case_runtime.stdout)
        assert "file.lua:2" in case_formatted, case_formatted
        assert "> 2 | return value + 1" in case_formatted, case_formatted

    # Invalid maps report a useful CLI error.
    invalid_map = fallback_dir / "invalid.map"
    invalid_map.write_text("{not valid JSON", encoding="utf-8")
    fail(traceback_command(invalid_map), fallback_dir, "Invalid source map")

    # A map path that aliases the generated file must be rejected before any
    # output is written over it.
    same_path = fallback_dir / "same output.lua"
    same_source = "print('keep the Lua output intact')\n"
    same_path.write_text(same_source, encoding="utf-8", newline="")
    fail(lua_cli("--preset", "Minify", "--out", same_path.name, "--source-map", same_path.name,
                 same_path.name, cwd=fallback_dir), fallback_dir, "must differ from the generated output path")
    assert same_path.read_text(encoding="utf-8") == same_source

    # Luau-only compounds and if-expressions survive both unparser layouts.
    luau_source = base / "luau-syntax.lua"
    luau_source.write_text('''local value = 1
value += 2
local message = if value == 3 then "ok" else "bad"
assert(message == "ok")
''', encoding="utf-8", newline="")
    for pretty in (False, True):
        luau_dir = base / f"luau-syntax-{int(pretty)}"
        luau_dir.mkdir()
        local_source = luau_dir / luau_source.name
        local_source.write_bytes(luau_source.read_bytes())
        output_path = luau_dir / "luau-output.lua"
        map_path = luau_dir / "luau-output.lua.map"
        generate(luau_dir, local_source, output_path, map_path, "LuaU", pretty)
        check([LUAU, str(output_path)], luau_dir)

    # Maps remain valid UTF-8 JSON when source bytes are not valid UTF-8. The
    # original source is represented by JSON null, while valid Unicode remains
    # embedded, and generated Lua preserves each source's runtime behavior.
    utf8_fixtures = {
        "invalid-literal": (
            b'local value = "\xff"\n'
            b'assert(string.byte(value) == 255)\n'
            b'print("invalid literal ok")\n',
            "invalid literal ok",
            False,
        ),
        "invalid-comment": (
            b'-- comment with invalid byte: \xff\n'
            b'assert(2 + 2 == 4)\n'
            b'print("invalid comment ok")\n',
            "invalid comment ok",
            False,
        ),
        "unicode": (
            'local value = "漢字🙂"\n'
            'assert(value == "漢字🙂")\n'
            'print("unicode ok")\n'.encode("utf-8"),
            "unicode ok",
            True,
        ),
    }
    for pretty in (False, True):
        utf8_dir = base / f"utf8-{int(pretty)}"
        utf8_dir.mkdir()
        for name, (source_bytes, expected_output, valid_source) in utf8_fixtures.items():
            source_path = utf8_dir / f"{name}.lua"
            source_path.write_bytes(source_bytes)
            output_path = utf8_dir / f"{name}.generated.lua"
            map_path = utf8_dir / f"{name}.generated.lua.map"
            args = ["--preset", "Minify", "--out", output_path.name,
                    "--source-map", map_path.name, "--Lua51"]
            if pretty:
                args.append("--pretty")
            args.append(source_path.name)
            build_log = check(lua_cli(*args, cwd=utf8_dir), utf8_dir)
            warning = "Omitting embedded source content for"
            if valid_source:
                assert warning not in build_log, build_log
            else:
                assert warning in build_log and "invalid UTF-8" in build_log, build_log

            source_map = json.loads(map_path.read_bytes())
            content = source_map["sourcesContent"][0]
            if valid_source:
                assert content == source_bytes.decode("utf-8"), source_map
            else:
                assert content is None, source_map

            for runtime in (LUA51, LUAU):
                output = check([runtime, str(output_path)], utf8_dir)
                assert expected_output in output, (runtime, output)

    # Omitting all sources suppresses the invalid-UTF-8 warning as well as
    # sourcesContent in the map.
    no_sources_dir = base / "utf8-no-sources"
    no_sources_dir.mkdir()
    invalid_path = no_sources_dir / "invalid.lua"
    invalid_path.write_bytes(utf8_fixtures["invalid-literal"][0])
    output_path = no_sources_dir / "generated.lua"
    map_path = no_sources_dir / "generated.lua.map"
    build_log = check(lua_cli("--preset", "Minify", "--Lua51", "--out", output_path.name,
                              "--source-map", map_path.name, "--source-map-no-sources",
                              invalid_path.name, cwd=no_sources_dir), no_sources_dir)
    assert "Omitting embedded source content" not in build_log, build_log
    assert "sourcesContent" not in json.loads(map_path.read_bytes())
    for runtime in (LUA51, LUAU):
        output = check([runtime, str(output_path)], no_sources_dir)
        assert "invalid literal ok" in output, (runtime, output)

print("Source map CLI integration checks passed")
